// SHA-256 of a string's UTF-8 bytes, as lowercase hex (pure JS, no native
// module: the app ships no hashing library). Used to check every registry
// file against the release manifest and every logo against its
// `logo.sha256`. A JSON or SVG file read as text and re-encoded in UTF-8
// gives back its exact bytes, so the hash matches `sha256sum` of the file.

